const dictionaries: Readonly<Record<Lang, Dictionary>> = { en, th };

const uiLanguage = (): string => {
  try {
    return browser.i18n.getUILanguage();
  } catch {
    return typeof navigator === "undefined" ? "" : navigator.language;
  }
};

export const resolveLang = (): Lang => (uiLanguage().toLowerCase().startsWith("th") ? "th" : "en");

export const dictionary = (lang: Lang = resolveLang()): Dictionary => dictionaries[lang];

export const describeError = (t: Dictionary, response: ErrorResponse): string =>
  response.error === "origin-mismatch"
    ? t.originMismatch(response.tabOrigin, response.savedOrigin)
    : t.errors[response.error];
